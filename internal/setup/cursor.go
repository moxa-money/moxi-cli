package setup

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
)

const cursorRules = `---
description: Founder shell rules (generated by moxi setup cursor)
globs:
alwaysApply: true
---

- Use moxi for local config, setup checks, and later the desk. Do not put account ids, state keys, or credentials in rules or chat.
- Founder config lives in the moxi config directory (default ~/.moxi). A context is a local label.
- Connect an MCP server only when a setup check names that server. Leave the editor config free of secrets until then.
- Copy mcp.json.example to mcp.json when a check asks for a server.
`

const mcpExample = `{
  "mcpServers": {}
}
`

// Cursor scaffolds editor rules and an example MCP file. Existing files are left in place.
func Cursor(dir string, out io.Writer) error {
	if dir == "" {
		var err error
		dir, err = os.Getwd()
		if err != nil {
			return err
		}
	}
	base := filepath.Join(dir, ".cursor")
	if err := os.MkdirAll(base, 0o755); err != nil {
		return err
	}
	rulesPath := filepath.Join(base, "rules", "founder.mdc")
	if err := os.MkdirAll(filepath.Dir(rulesPath), 0o755); err != nil {
		return err
	}
	if err := writeIfMissing(out, rulesPath, cursorRules); err != nil {
		return err
	}
	mcpPath := filepath.Join(base, "mcp.json.example")
	if err := writeIfMissing(out, mcpPath, mcpExample); err != nil {
		return err
	}
	fmt.Fprintf(out, "scaffolded %s\n", base)
	fmt.Fprintf(out, "  rules: %s\n", rulesPath)
	fmt.Fprintf(out, "  example: %s (copy to mcp.json when a check names a server)\n", mcpPath)
	return nil
}

func writeIfMissing(out io.Writer, path, content string) error {
	if _, err := os.Stat(path); err == nil {
		fmt.Fprintf(out, "  skip (exists): %s\n", path)
		return nil
	} else if !os.IsNotExist(err) {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}
